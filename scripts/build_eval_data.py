"""Build data/eval/: DE sets, scoring set, dense targets and split files (phase 4a spec §5 step 1).

`make eval-data`. Tahoe's DESeq2 rows are fetched once per eligible cell line, each line in its own subprocess
(`--fetch-line`) so memory is returned after every line (spec E9); fetched lines are kept in data/eval/de_raw/
and skipped on a re-run. Footer probes are cached in data/cache/tahoe_de_probes.parquet.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from phase1.stream import connect  # noqa: E402
from phase3.config import DOSE_UNIT_TO_UM, load_features_config  # noqa: E402
from phase3.crosscheck import select_condition_rows  # noqa: E402
from phase3.layer import load_condition_features  # noqa: E402
from phase4 import contracts, splits, targets, tahoe_de  # noqa: E402

EVAL_CONFIG = ROOT / "configs" / "eval.yaml"
CONDITIONS = ROOT / "data" / "pseudobulk" / "conditions.parquet"
LOGFC = ROOT / "data" / "pseudobulk" / "logfc.parquet"
GENES = ROOT / "data" / "pseudobulk" / "genes.parquet"
FEATURES_DIR = ROOT / "data" / "features"
EXPRESSION = ROOT / "data" / "cache" / "depmap" / "OmicsExpressionProteinCodingGenesTPMLogp1.parquet"
EVAL_DIR = ROOT / "data" / "eval"
RAW_DIR = EVAL_DIR / "de_raw"
CANDIDATES = EVAL_DIR / "candidates.parquet"
PROBES = ROOT / "data" / "cache" / "tahoe_de_probes.parquet"
SCRATCH = ROOT / "data" / "cache" / "de_eval_tmp"
REPORT = ROOT / "reports" / "eval_data.md"


def load_eval_config() -> dict:
    return yaml.safe_load(EVAL_CONFIG.read_text(encoding="utf-8"))


def assemble(view: pd.DataFrame, eligible: set[str], de_sets: pd.DataFrame, universe: pd.DataFrame, drug_groups: pd.DataFrame,
             cfg: dict, forbidden_test_lines: set[str]) -> dict:
    """Everything in data/eval/ except the target matrix, validated against the phase 4a contracts.

    `de_sets` comes from `targets.prepare_de_sets` (filtered, ranked and capped in DuckDB).
    """
    scoring, exclusions = targets.scoring_set(view, eligible, de_sets, cfg["min_de_genes"])
    scoring = scoring.sort_values("condition_id").reset_index(drop=True)
    de_sets = de_sets[de_sets["condition_id"].isin(set(scoring["condition_id"]))].reset_index(drop=True)
    drawn = splits.draw_splits(scoring, drug_groups, cfg)
    contracts.validate_de_sets(de_sets, set(scoring["condition_id"]), cfg["min_de_genes"])
    contracts.validate_splits(drawn, scoring, drug_groups, forbidden_test_lines)
    return {
        "conditions": scoring,
        "genes": universe[["gene", "gene_symbol"]].reset_index(drop=True),
        "de_sets": de_sets,
        "splits": drawn,
        "exclusions": exclusions,
        "sizes": splits.split_sizes(drawn, scoring),
    }


def fetch_line(cell_line: str, cap_gb: float) -> None:
    """Subprocess body: fetch one line's plates 1-3 DE rows and map them to our candidate conditions."""
    tahoe_de.set_revision(load_features_config()["tahoe"]["revision"])
    candidates = pd.read_parquet(CANDIDATES)
    mine = candidates[candidates["cell_line"] == cell_line]
    cache = tahoe_de.load_probe_cache(PROBES)
    budget = tahoe_de.NetworkBudget(int(cap_gb * 1e9))
    con_remote, con_local = connect("1GB", remote=True), connect("2GB")
    coarse = tahoe_de.build_coarse_index(con_remote, cache, budget)
    rows, start, notes = tahoe_de.fetch_cell_line_plates_1_3(
        con_remote, con_local, cell_line, coarse, cache, budget, set(mine["drug"]), SCRATCH
    )
    tahoe_de.save_probe_cache(cache, PROBES)
    if start is None:
        raise SystemExit(f"{cell_line}: not located in Tahoe's DE table ({'; '.join(notes)})")
    rows = rows.rename(columns={"gene_name": "gene_symbol"})
    parts = []
    for cond in mine.itertuples():
        sel = select_condition_rows(rows, plate=cond.plate.removeprefix("plate"), drug=cond.drug, dose_um=cond.dose * DOSE_UNIT_TO_UM[cond.unit])
        if len(sel):
            parts.append(sel[["gene_symbol", "log2FoldChange", "padj"]].assign(condition_id=cond.condition_id))
    out = pd.concat(parts, ignore_index=True) if parts else pd.DataFrame(columns=["gene_symbol", "log2FoldChange", "padj", "condition_id"])
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    out.to_parquet(RAW_DIR / f"{cell_line}.parquet", index=False)
    print(f"{cell_line}: {out['condition_id'].nunique()}/{len(mine)} conditions, {budget.n_downloads} shards, "
          f"{budget.spent / 1e6:.0f} MB; {'; '.join(notes) or 'ok'}", flush=True)


def write_report(built: dict, eligible: set[str], universe: pd.DataFrame) -> None:
    sizes = built["sizes"]
    lines = [
        "# Evaluation data",
        "",
        "Generated by `make eval-data`; do not edit.",
        "",
        f"- Eligible cell lines (evaluation.md A2): {len(eligible)}",
        f"- Gene universe: {len(universe)} DepMap protein-coding genes matched to ours "
        f"({universe.attrs.get('n_not_in_ours', 0)} DepMap symbols not in ours, {universe.attrs.get('n_duplicate_symbols', 0)} duplicates)",
        f"- Scoring set: {len(built['conditions'])} conditions; DE genes per condition: median "
        f"{int(built['de_sets'].groupby('condition_id').size().median())}",
        "",
        "## Exclusions (first failing rule)",
        "",
        "| reason | conditions |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in built["exclusions"].items()],
        "",
        "## Split sizes (conditions per part; test lines / drugs)",
        "",
        "| repeat | split | train | val | test | test lines | test drugs |",
        "|---|---|---|---|---|---|---|",
        *[f"| {r.repeat} | {r.split} | {r.train} | {r.val} | {r.test} | {int(r.test_lines)} | {int(r.test_drugs)} |" for r in sizes.itertuples()],
        "",
    ]
    small = sizes[(sizes["split"] == "both_unseen") & (sizes["test"] < 200)]
    if len(small):
        lines.append(f"**Note:** {len(small)} both_unseen repeat(s) have fewer than 200 test conditions (spec §10).")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fetch-line", help="internal: fetch one cell line's DE rows (run in a subprocess)")
    args = parser.parse_args()
    cfg = load_eval_config()
    cap_gb = cfg["de_fetch"]["per_line_network_cap_gb"]
    if args.fetch_line:
        fetch_line(args.fetch_line, cap_gb)
        return

    con = connect("2GB")
    conditions = pd.read_parquet(CONDITIONS)
    with_logfc = {r[0] for r in con.execute(f"SELECT DISTINCT condition_id FROM read_parquet('{LOGFC}')").fetchall()}
    eligible = targets.eligible_lines(conditions, with_logfc, cfg["split_eligibility"]["min_fraction_treated_with_logfc"])
    view = load_condition_features(CONDITIONS, FEATURES_DIR)
    view = view[view["condition_id"].isin(with_logfc) | view["is_control"]]
    candidates = view[~view["is_control"] & view["cell_line"].isin(eligible) & view["features_complete"]]
    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    candidates[["condition_id", "cell_line", "drug", "dose", "unit", "plate"]].to_parquet(CANDIDATES, index=False)

    for line in sorted(set(candidates["cell_line"])):
        if not (RAW_DIR / f"{line}.parquet").exists():
            subprocess.run([sys.executable, __file__, "--fetch-line", line], check=True)
    universe = targets.gene_universe(EXPRESSION, pd.read_parquet(GENES))
    de_sets = targets.prepare_de_sets(con, sorted(RAW_DIR.glob("*.parquet")), set(universe["gene_symbol"]), cfg)
    drug_groups = pd.read_parquet(FEATURES_DIR / "drug_groups.parquet")
    all_lines = set(conditions["cell_line"])
    gap_lines = set(view.loc[~view["is_control"] & ~view["features_complete"], "cell_line"])
    built = assemble(view, eligible, de_sets, universe, drug_groups, cfg, forbidden_test_lines=(all_lines - eligible) | gap_lines)

    matrix = targets.build_targets(con, LOGFC, built["conditions"], built["genes"])
    contracts.validate_targets(matrix, built["conditions"], built["genes"])
    built["conditions"].to_parquet(EVAL_DIR / "conditions.parquet", index=False)
    built["genes"].to_parquet(EVAL_DIR / "genes.parquet", index=False)
    np.save(EVAL_DIR / "targets.npy", matrix)
    built["de_sets"].to_parquet(EVAL_DIR / "de_sets.parquet", index=False)
    built["splits"].to_parquet(EVAL_DIR / "splits.parquet", index=False)
    write_report(built, eligible, universe)
    print(f"eval data: {len(built['conditions'])} conditions x {len(built['genes'])} genes; report {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
